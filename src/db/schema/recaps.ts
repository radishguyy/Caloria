import {
  pgTable,
  uuid,
  timestamp,
  integer,
  jsonb,
  boolean,
  pgEnum,
  index,
} from "drizzle-orm/pg-core";
import { users } from "./users";

export const recapTypeEnum = pgEnum("recap_type", ["weekly", "monthly"]);

export const recaps = pgTable(
  "recaps",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    userId: uuid("user_id")
      .references(() => users.id, { onDelete: "cascade" })
      .notNull(),
    type: recapTypeEnum("type").default("weekly").notNull(),
    cycleNumber: integer("cycle_number").notNull(), // Week 1, Week 2, Month 1, etc.
    startDate: timestamp("start_date").notNull(),
    endDate: timestamp("end_date").notNull(),
    unlockDate: timestamp("unlock_date").notNull(),
    isViewed: boolean("is_viewed").default(false).notNull(),
    slidesData: jsonb("slides_data"), // Cached structured JSON generated by Gemini
    createdAt: timestamp("created_at").defaultNow().notNull(),
  },
  (table) => [
    index("recaps_user_id_idx").on(table.userId),
    index("recaps_user_type_cycle_idx").on(table.userId, table.type, table.cycleNumber),
  ]
);

export type Recap = typeof recaps.$inferSelect;
export type NewRecap = typeof recaps.$inferInsert;

