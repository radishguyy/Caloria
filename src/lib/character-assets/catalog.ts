export function getCharacterDefinition(id: string): CharacterDefinition {
  return (
    CHARACTER_CATALOG.find((c) => c.id === id) || CHARACTER_CATALOG[0]
  );
}

export function getAccessoryDefinition(id?: string | null): AccessoryDefinition | undefined {
  if (!id || id.endsWith("-none") || id === "skin-default" || id === "room-default") {
    return undefined;
  }
  return ACCESSORY_CATALOG.find((a) => a.id === id);
}

export function isAccessoryCompatible(
  characterId: CharacterId,
  accessoryId: string
): boolean {
  const acc = getAccessoryDefinition(accessoryId);
  if (!acc) return true;
  if (acc.compatibleCharacters === "all") return true;
  return acc.compatibleCharacters.includes(characterId);
}

/**
 * Resolves the SVG transform string (`translate(...) rotate(...) scale(...)`)
 * for an accessory placed on a specific character, combining:
 * 1. The character's anchor adjustment for `accessory.anchor`
 * 2. Any character-specific override on the accessory or character definition
 */
export function resolveAccessoryTransform(
  characterId: CharacterId,
  accessory: AccessoryDefinition
): string {
  const character = getCharacterDefinition(characterId);
  const anchorPoint = CHARACTER_ANCHORS[accessory.anchor] || { x: 64, y: 80 };

  const charAnchorAdj: AnchorTransform =
    character.anchorAdjustments?.[accessory.anchor] || {};
  const accCharAdj: AnchorTransform =
    accessory.characterAdjustments?.[characterId] ||
    character.accessoryOverrides?.[accessory.id] ||
    {};

  const dx = (charAnchorAdj.dx ?? 0) + (accCharAdj.dx ?? 0);
  const dy = (charAnchorAdj.dy ?? 0) + (accCharAdj.dy ?? 0);
  const scale =
    (accessory.scale ?? 1) *
    (charAnchorAdj.scale ?? 1) *
    (accCharAdj.scale ?? 1);
  const rotate = (charAnchorAdj.rotate ?? 0) + (accCharAdj.rotate ?? 0);

  if (dx === 0 && dy === 0 && scale === 1 && rotate === 0) {
    return "";
  }

  // Transform around the intended anchor point (anchorPoint.x, anchorPoint.y)
  const cx = anchorPoint.x;
  const cy = anchorPoint.y;

  const parts: string[] = [];
  if (dx !== 0 || dy !== 0) {
    parts.push(`translate(${dx} ${dy})`);
  }
  if (rotate !== 0) {
    parts.push(`rotate(${rotate} ${cx} ${cy})`);
  }
  if (scale !== 1) {
    parts.push(
      `translate(${cx} ${cy}) scale(${Number(scale.toFixed(3))}) translate(${-cx} ${-cy})`
    );
  }
  return parts.join(" ");
}

